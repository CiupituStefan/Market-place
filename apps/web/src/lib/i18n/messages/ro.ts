const plural = (count: number, one: string, many: string) =>
  // Romanian adds "de" from 20 up ("20 de produse"), except numbers ending in 01–19.
  count === 1
    ? `1 ${one}`
    : count % 100 >= 20 || (count % 100 === 0 && count !== 0)
      ? `${String(count)} de ${many}`
      : `${String(count)} ${many}`;

